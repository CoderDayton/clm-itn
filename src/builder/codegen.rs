fn vocab(v: &Vocab) -> String {
    format!(
        "crate::tables::Vocab {{ names: {:?}, name_id: {:?}, months: {:?}, hours: {:?}, \
centuries: {:?}, zones: {:?}, not_after_number: {:#x}, not_before_number: {:#x} }}",
        v.names,
        v.name_id,
        v.months,
        v.hours,
        v.centuries,
        v.zones,
        v.not_after_number,
        v.not_before_number
    )
}

fn mode<T: Copy + Eq + std::hash::Hash>(values: &[T]) -> T {
    let mut counts: HashMap<T, usize> = HashMap::new();
    for &v in values {
        *counts.entry(v).or_default() += 1;
    }
    let mut best = values[0];
    for (i, &v) in values.iter().enumerate() {
        if counts[&v] > counts[&best] || (counts[&v] == counts[&best] && i == 0) {
            best = v;
        }
    }
    best
}

fn fill<T, F>(ty: &str, values: &[T], base: T, show: F) -> String
where
    T: Copy + Eq,
    F: Fn(T) -> String,
{
    let n = values.len();
    let mut s = format!(
        "{{\n        let mut a: [{ty}; {n}] = [{}; {n}];\n",
        show(base)
    );
    for (i, &v) in values.iter().enumerate() {
        if v != base {
            let _ = writeln!(s, "        a[{i}] = {};", show(v));
        }
    }
    s.push_str("        a\n    }");
    s
}

fn sparse<T: Copy + Eq + std::hash::Hash + std::fmt::Display>(ty: &str, values: &[T]) -> String {
    fill(ty, values, mode(values), |v| v.to_string())
}

fn sparse_hex(values: &[u64]) -> String {
    fill("u64", values, 0, |v| format!("{v:#x}"))
}

fn bytes(b: &[u8]) -> String {
    let mut s = String::from("*b\"");
    for &c in b {
        if c.is_ascii_alphanumeric() {
            s.push(c as char);
        } else {
            let _ = write!(s, "\\x{c:02x}");
        }
    }
    s.push('"');
    s
}

fn keys(k: &[Key; 4]) -> String {
    let parts: Vec<String> = k.iter().map(|k| bytes(k)).collect();
    format!("[{}]", parts.join(", "))
}

fn lexicon(t: &Tables) -> String {
    let lx = &t.lexicon;
    let mut b = String::from(
        "{\n        let mut a = [crate::tables::lexicon::Bucket::EMPTY; crate::tables::lexicon::BUCKETS];\n",
    );
    for (i, bucket) in lx.buckets().iter().enumerate() {
        if *bucket != crate::tables::lexicon::Bucket::EMPTY {
            let _ = writeln!(
                b,
                "        a[{i}] = crate::tables::lexicon::Bucket::from_keys({});",
                keys(bucket.keys())
            );
        }
    }
    b.push_str("        a\n    }");
    format!(
        "crate::tables::lexicon::Lexicon::from_raw({b}, {}, {:#x}, {})",
        fill("u32", &lx.payload()[..], 0, |v| format!("{v:#x}")),
        lx.seed(),
        lx.buckets_used()
    )
}

fn shapes(t: &Tables) -> String {
    let mut b = String::from(
        "{\n        let mut a = [crate::tables::shape::ShapeBucket::EMPTY; crate::tables::shape::SHAPE_BUCKETS];\n",
    );
    for (i, bucket) in t.shapes.buckets().iter().enumerate() {
        if *bucket != crate::tables::shape::ShapeBucket::EMPTY {
            let k: Vec<String> = bucket.keys().iter().map(|k| format!("{k:#x}")).collect();
            let ids: Vec<String> = bucket.ids().iter().map(u16::to_string).collect();
            debug_assert_eq!(k.len(), SHAPE_SLOTS);
            let _ = writeln!(
                b,
                "        a[{i}] = crate::tables::shape::ShapeBucket::from_raw([{}], [{}]);",
                k.join(", "),
                ids.join(", ")
            );
        }
    }
    b.push_str("        a\n    }");
    format!(
        "crate::tables::shape::ShapeTable::from_raw({b}, {:#x})",
        t.shapes.seed()
    )
}

fn candidate(c: &Candidate) -> String {
    let ops: Vec<String> = c.ops.iter().map(|o| format!("{o:#x}")).collect();
    format!(
        "crate::tables::candidate::Candidate {{ span_len: {}, op_count: {}, _pad: [{}, {}], ops: [{}] }}",
        c.span_len,
        c.op_count,
        c._pad[0],
        c._pad[1],
        ops.join(", ")
    )
}

fn candidates(t: &Tables) -> String {
    let c = &t.candidates;
    let empty = Candidate::default();
    let mut records = String::from(
        "{\n        let mut a = [[crate::tables::candidate::Candidate::new(0, &[]); crate::tables::candidate::CANDIDATES]; crate::types::DOMAIN_COUNT];\n",
    );
    for (d, row) in c.all_records().iter().enumerate() {
        for (i, r) in row.iter().enumerate() {
            if *r != empty {
                let _ = writeln!(records, "        a[{d}][{i}] = {};", candidate(r));
            }
        }
    }
    records.push_str("        a\n    }");
    let mut literals = String::from(
        "{\n        let mut a = [[0u8; crate::tables::candidate::MAX_LITERAL_LEN]; crate::tables::candidate::MAX_LITERALS];\n",
    );
    for (i, lit) in c.literals().iter().enumerate() {
        if lit.iter().any(|&b| b != 0) {
            let _ = writeln!(literals, "        a[{i}] = {};", bytes(lit));
        }
    }
    literals.push_str("        a\n    }");
    format!(
        "crate::tables::candidate::CandidateTable::from_raw({records}, {literals}, {}, {})",
        sparse("u8", &c.literal_lens()[..]),
        c.literal_count()
    )
}
